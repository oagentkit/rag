package ontology

// Entity 实体实例（本体层的节点面）：叫什么 + 是什么类型。
//
// 实体的字段取值由三元组承载（谓词 = 字段名，客体 = 字段取值），
// 因此 Entity 不重复存一份字段表——数据只有一处，判据与查询面才不会分叉。
//
// 实体名由宿主按领域约定给出；**本包不做实体名规范化**
// （大小写折叠、别名归一、环境前缀剥离等规则属领域资产，留在宿主）。
type Entity struct {
	// Name 实体名（三元组的主体/引用目标都用它）。
	Name string
	// Type 实体类型名，必须在 Schema 内声明。
	Type string
}
